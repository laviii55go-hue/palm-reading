/** 外（算命学）×内（数秘術）の関係判定 */
export function crossRelation(outer: AxisKey, inner: AxisKey): CrossRelation {
  if (outer === inner) return "resonance";
  const o = AXIS_ORDER.indexOf(outer);
  const n = AXIS_ORDER.indexOf(inner);
  if ((o + 1) % 5 === n || (n + 1) % 5 === o) return "support"; // 相生（双方向）
  return "duality"; // 相剋
}

