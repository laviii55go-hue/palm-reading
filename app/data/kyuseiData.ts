/**
 * 本命星の計算（立春区切り）
 * 1) 生年を立春区切りで補正（立春前生まれは前年扱い・太陽黄経の天文計算）
 * 2) 西暦の各桁を一桁になるまで足す（数字根）
 * 3) 11 − 数字根。結果が 10 以上なら 9 を引く
 */
export function calcHonmeisei(year: number, month: number, day: number): number {
  const kyuseiYear = sanmeiYearNumber(year, month, day);
  let s = String(kyuseiYear)
    .split("")
    .map(Number)
    .reduce((a, b) => a + b, 0);
  while (s > 9) {
    s = String(s)
      .split("")
      .map(Number)
      .reduce((a, b) => a + b, 0);
  }
  const star = 11 - s;
  return star > 9 ? star - 9 : star;
}

/** 立春区切り後の「九星上の年」も返すユーティリティ（結果画面の注記用） */
export function kyuseiYearOf(year: number, month: number, day: number): number {
  return sanmeiYearNumber(year, month, day);
}
